'use strict';

const { tokenize } = require('./tokenize');

const MODEL_VERSION = 2;

function toTokenMap(tokens) {
    const map = Object.create(null);
    const keys = Object.keys(tokens).sort();
    for (let i = 0; i < keys.length; i += 1) {
        map[keys[i]] = tokens[keys[i]];
    }
    return map;
}

function tokenCount(tokens, token) {
    return Object.prototype.hasOwnProperty.call(tokens, token) ? tokens[token] : 0;
}

/**
 * Bernoulli-style naive Bayes over de-duplicated code tokens.
 * Each training sample contributes a token at most once.
 */
class Classifier {
    constructor() {
        this.classes = Object.create(null);
    }

    addDocument(text, label) {
        if (typeof label !== 'string' || label.length === 0) {
            throw new TypeError('Expected a language label');
        }
        const tokens = tokenize(text);
        if (tokens.length === 0) {
            return;
        }
        if (!this.classes[label]) {
            this.classes[label] = { docs: 0, tokens: Object.create(null) };
        }
        const entry = this.classes[label];
        entry.docs += 1;
        for (let i = 0; i < tokens.length; i += 1) {
            const token = tokens[i];
            entry.tokens[token] = (entry.tokens[token] || 0) + 1;
        }
    }

    vocabulary() {
        const vocab = new Set();
        const labels = Object.keys(this.classes);
        for (let i = 0; i < labels.length; i += 1) {
            const tokens = this.classes[labels[i]].tokens;
            const keys = Object.keys(tokens);
            for (let j = 0; j < keys.length; j += 1) {
                vocab.add(keys[j]);
            }
        }
        return vocab;
    }

    languages() {
        return Object.keys(this.classes).sort();
    }

    /**
     * @param {string} text
     * @returns {{language: string, scores: {language: string, score: number}[]}|null}
     */
    classify(text) {
        const tokens = tokenize(text);
        const labels = this.languages();
        if (labels.length === 0 || tokens.length === 0) {
            return null;
        }

        const vocab = this.vocabulary();
        const known = [];
        for (let i = 0; i < tokens.length; i += 1) {
            if (vocab.has(tokens[i])) {
                known.push(tokens[i]);
            }
        }
        if (known.length === 0) {
            return null;
        }

        let totalDocs = 0;
        const totals = Object.create(null);
        for (let i = 0; i < labels.length; i += 1) {
            const entry = this.classes[labels[i]];
            totalDocs += entry.docs;
            let total = 0;
            const keys = Object.keys(entry.tokens);
            for (let j = 0; j < keys.length; j += 1) {
                total += tokenCount(entry.tokens, keys[j]);
            }
            totals[labels[i]] = total;
        }

        const vocabSize = vocab.size;
        const logs = new Array(labels.length);
        for (let i = 0; i < labels.length; i += 1) {
            const label = labels[i];
            const entry = this.classes[label];
            const denom = totals[label] + vocabSize;
            let log = Math.log(entry.docs / totalDocs);
            for (let j = 0; j < known.length; j += 1) {
                const count = tokenCount(entry.tokens, known[j]);
                log += Math.log((count + 1) / denom);
            }
            logs[i] = log;
        }

        let maxLog = logs[0];
        for (let i = 1; i < logs.length; i += 1) {
            if (logs[i] > maxLog) {
                maxLog = logs[i];
            }
        }

        const weights = new Array(logs.length);
        let weightSum = 0;
        for (let i = 0; i < logs.length; i += 1) {
            const weight = Math.exp(logs[i] - maxLog);
            weights[i] = weight;
            weightSum += weight;
        }

        const scores = [];
        for (let i = 0; i < labels.length; i += 1) {
            scores.push({
                language: labels[i],
                score: weights[i] / weightSum
            });
        }
        scores.sort(function (a, b) {
            return b.score - a.score || a.language.localeCompare(b.language);
        });

        return {
            language: scores[0].language,
            scores: scores
        };
    }

    toJSON() {
        const classes = {};
        const labels = this.languages();
        for (let i = 0; i < labels.length; i += 1) {
            const entry = this.classes[labels[i]];
            classes[labels[i]] = {
                docs: entry.docs,
                tokens: toTokenMap(entry.tokens)
            };
        }
        return {
            version: MODEL_VERSION,
            source: 'Generated by npm run train. Do not edit by hand.',
            classes: classes
        };
    }

    static restore(data) {
        if (!data || data.version !== MODEL_VERSION || !data.classes) {
            throw new Error('Unsupported classifier model. Run `npm run train`.');
        }
        const classifier = new Classifier();
        const labels = Object.keys(data.classes);
        for (let i = 0; i < labels.length; i += 1) {
            const entry = data.classes[labels[i]];
            if (!entry || typeof entry.docs !== 'number' || !entry.tokens) {
                throw new Error('Classifier model is missing class "' + labels[i] + '"');
            }
            classifier.classes[labels[i]] = {
                docs: entry.docs,
                tokens: toTokenMap(entry.tokens)
            };
        }
        return classifier;
    }
}

module.exports = {
    Classifier: Classifier
};
